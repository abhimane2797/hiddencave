export function createSeedBookings(now = new Date()): Booking[] {
  const today = new Date(now)
  return specs.map((spec, i) => ({
    id: `BK-${1101 + i}`,
    customerName: spec.customerName,
    mobile: spec.mobile,
    date: dateKey(addDays(today, spec.dayOffset)),
    startTime: spec.startTime,
    durationMinutes: spec.durationMinutes,
    stationId: spec.stationId,
    players: spec.players,
    packageId: spec.players > 1 ? 'multiplayer' : spec.durationMinutes > 60 ? 'two-hour' : 'one-hour',
    status: spec.status,
    amount: spec.amount,
    paymentMethod: spec.paymentMethod,
    paymentStatus: spec.paymentStatus,
    notes: spec.notes,
    createdAt: new Date(now.getTime() - (spec.dayOffset <= 0 ? 3 : -2) * 36e5).toISOString(),
  }))
}